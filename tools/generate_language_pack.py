"""Build one shared downloadable English UI pack and bounded native decoder tables."""
from pathlib import Path
import collections,heapq,itertools,json,zlib,struct
ROOT=Path(__file__).resolve().parents[1]
PROJECTS=['time2','core2duo','time-pebble2','round2','timeround']
def generate():
 pairs={}
 for name in PROJECTS:
  for de,en in json.loads((ROOT/'projects'/name/'tools/translations.json').read_text()).items():
   if de in pairs and pairs[de]!=en:raise ValueError('Conflicting translation '+de)
   pairs[de]=en
 short=sorted((de,en) for de,en in pairs.items() if len(en.encode())<=60)
 parts=[list(en.encode())+[0] for de,en in short];dictionary=[]
 for i in range(192):
  freq=collections.Counter((s[j],s[j+1]) for s in parts for j in range(len(s)-1) if s[j] and s[j+1])
  pair,count=min(freq.items(),key=lambda x:(-x[1],x[0]))
  if count<2:break
  dictionary.append(pair)
  for k,s in enumerate(parts):
   out=[];j=0
   while j<len(s):
    if j+1<len(s) and tuple(s[j:j+2])==pair:out.append(256+i);j+=2
    else:out.append(s[j]);j+=1
   parts[k]=out
 freq=collections.Counter(v for s in parts for v in s);serial=itertools.count();heap=[(n,next(serial),v) for v,n in sorted(freq.items())];heapq.heapify(heap)
 while len(heap)>1:
  a=heapq.heappop(heap);b=heapq.heappop(heap);heapq.heappush(heap,(a[0]+b[0],next(serial),(a[2],b[2])))
 tree=[];codes={}
 def visit(node,code):
  if isinstance(node,int):codes[node]=code;return -node-1
  index=len(tree);tree.append(None);left=visit(node[0],code+[0]);right=visit(node[1],code+[1]);tree[index]=(left,right);return index
 visit(heap[0][2],[]);bits=[];offsets=[]
 for seq in parts:
  offsets.append(len(bits))
  for token in seq:bits.extend(codes[token])
 payload=bytes(sum((bits[i+j] if i+j<len(bits) else 0)<<(7-j) for j in range(8)) for i in range(0,len(bits),8))
 assert len(payload)<=2400
 crc=zlib.crc32(payload);identity=zlib.crc32(b'LP2/128'+json.dumps([short,dictionary,tree],ensure_ascii=False,separators=(',',':')).encode()+payload)
 packet=dict(id=identity,crc=crc,size=len(payload),chunks=[payload[i:i+128].hex() for i in range(0,len(payload),128)])
 runtime=(ROOT/'tools/language_pack_runtime.c').read_text()
 for name in PROJECTS:
  folder=ROOT/'projects'/name;local=json.loads((folder/'tools/translations.json').read_text())
  lines=['/* Generated by tools/generate_language_pack.py. English UI text arrives from the phone. */','#include "i18n.h"','#include <pebble.h>','#include <string.h>','#include <stddef.h>',f'#define PACK_ID {identity}u',f'#define PACK_CRC {crc}u',f'#define PACK_SIZE {len(payload)}',f'#define PACK_PARTS {len(packet["chunks"])}','typedef struct {const char *de;uint16_t bit;} PackedText;','static const PackedText packed_texts[]={']
  lines += ['{'+json.dumps(de,ensure_ascii=False)+','+str(offset)+'},' for (de,en),offset in zip(short,offsets)]
  lines += ['};','typedef struct {const char *de,*en;} LongText;','static const LongText long_texts[]={']
  lines += ['{'+json.dumps(de,ensure_ascii=False)+','+json.dumps(en,ensure_ascii=False)+'},' for de,en in local.items() if len(en.encode())>60]
  lines += ['};',f'#define TOKEN_COUNT {len(dictionary)}',f'#define TREE_COUNT {len(tree)}',runtime]
  codec=b''.join(struct.pack('<HH',a,b) for a,b in dictionary)+b''.join(struct.pack('<hh',a,b) for a,b in tree)
  (folder/'resources/data').mkdir(exist_ok=True)
  (folder/'resources/data/language-codec.bin').write_bytes(codec)
  package=json.loads((folder/'package.json').read_text())
  if not any(x['name']=='LANGUAGE_CODEC' for x in package['pebble']['resources']['media']):package['pebble']['resources']['media'].append(dict(type='raw',name='LANGUAGE_CODEC',file='data/language-codec.bin'))
  (folder/'package.json').write_text(json.dumps(package,ensure_ascii=False,indent=2)+'\n')
  (folder/'src/c/i18n.c').write_text('\n'.join(lines)+'\n')
  (folder/'src/pkjs/lang-pack.js').write_text('module.exports = '+json.dumps(packet,separators=(',',':'))+';\n')
  fixture=['static const unsigned char fixture_codec[]={'+','.join(str(x) for x in codec)+'};','static const unsigned fixture_id='+str(identity)+'u;','static const char *fixture_chunks[]={']+[json.dumps(x)+',' for x in packet['chunks']]+['};','static const char *fixture_pairs[][2]={']+['{'+json.dumps(de,ensure_ascii=False)+','+json.dumps(en,ensure_ascii=False)+'},' for de,en in local.items()]+['};']
  (folder/'tests/language_pack_fixture.h').write_text('\n'.join(fixture)+'\n')

 (ROOT/'docs/language-pack-metrics.json').write_text(json.dumps(dict(strings=len(short),bytes=len(payload),parts=len(packet['chunks']),id=identity,crc=crc,maxTextBytes=60),indent=2)+'\n')
 return packet
if __name__=='__main__':print('English UI language pack:',generate()['size'],'bytes')
